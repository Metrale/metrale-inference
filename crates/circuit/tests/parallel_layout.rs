//! 2026-10-23: The parallel layout report of every multi-device instance
//! (kernels/circuits/plans/parallel/): each part's degree, group and per-rank slice, the derived
//! collectives per rank, and the cost model's ranking of today's layout against every one-part
//! change (candidates to measure, never a change to the serve). Regenerate after an intended
//! change with `cargo test -p metrale-circuit --test parallel_layout -- --ignored regenerate`.
//!
//! Owner: metrale-circuit tests.
//! Invariants: nothing is written except by the ignored `regenerate`.

mod common;
#[path = "parallel_layout/rotate.rs"]
mod rotate;

use std::collections::BTreeMap;
use std::fmt::Write as _;

use metrale_circuit::ir::{Circuit, OpKind};
use metrale_circuit::parallel::{self, ParallelSpec};
use metrale_circuit::parallel_cost::{Link, parse_link, rank_cost, segmented, step_us};
use metrale_circuit::{Deployment, Instance};

const DIR: &str = "kernels/circuits/plans/parallel";
const COMMAND: &str = "cargo test -p metrale-circuit --test parallel_layout -- --ignored regenerate";

fn spec_of(t: &common::Texts) -> ParallelSpec {
    let blocks: Vec<(&str, &str)> = t.blocks.iter().map(|(n, s)| (n.as_str(), s.as_str())).collect();
    metrale_circuit::parallel_spec(&t.circuit, &blocks).unwrap()
}

fn ranks(inst: &Instance, t: &common::Texts) -> Result<Vec<Circuit>, String> {
    common::load_texts(inst, t).map(|l| l.ranks).map_err(|e| e.to_string())
}

fn dram_gbps(inst: &Instance) -> f64 {
    let reg = metrale_circuit::hardware::parse_devices(&common::read("kernels/DEVICES.toml")).unwrap();
    let hw = inst.target.split('/').next().unwrap();
    reg.devices.iter().find(|d| d.id == hw).expect("the target's device").bandwidth_gbps
}

fn link(inst: &Instance) -> (Link, String) {
    let hw = inst.target.split('/').next().unwrap();
    parse_link(&common::read(&format!("kernels/{hw}/HARDWARE.toml")))
        .unwrap()
        .expect("the class states its collective link")
}

fn slug(inst: &Instance) -> String {
    let hw = inst.target.split('/').next().unwrap();
    format!("{}--{hw}", inst.recipe.rsplit('/').next().unwrap())
}

fn report(inst: &Instance) -> String {
    let t = common::Texts::of(inst);
    let spec = spec_of(&t);
    let d: &Deployment = inst.parallel.as_ref().unwrap();
    let today = ranks(inst, &t).unwrap();
    let layout = common::load_texts(inst, &t).unwrap().layout.unwrap();
    let mut s = String::new();
    let _ = writeln!(
        s,
        "# Parallel layout: `{}`\n\nGenerated by `{COMMAND}`. Do not edit: the check test fails on a stale copy.\n\n\
         One circuit (`kernels/circuits/{}.toml`, its `[parallel]` spec) instantiated at each rank of the \
         deployment `kernels/circuits/INSTANCES.toml [instance.parallel]` states (crates/circuit/src/parallel.rs). \
         N = {} ({}).\n",
        inst.recipe, inst.arch, d.ranks, d.why
    );
    let _ = writeln!(s, "## Parts\n");
    let head: Vec<String> = (0..d.ranks).map(|r| format!("rank {r}")).collect();
    let _ = writeln!(s, "| dim | whole | unit | remainder | scope | degree | group | chosen | {} |", head.join(" | "));
    let _ = writeln!(s, "|---|---:|---:|---|---|---:|---|---|{}", "---:|".repeat(head.len()));
    for (dim, sp) in &spec {
        let p = &layout.parts[dim];
        let cells: Vec<String> = (0..d.ranks)
            .map(|rank| {
                let sl = parallel::slices(&spec, &inst.shape.dims, parallel::RankOf { layout: &layout, rank }).unwrap();
                match sl[dim] {
                    None => "idle".into(),
                    Some((start, len)) if p.splits() => format!("{len} @{start}"),
                    Some((_, len)) => format!("{len} (whole)"),
                }
            })
            .collect();
        let degree = match &sp.tie {
            Some(root) => format!("{} (tied to `{root}`)", p.degree),
            None => p.degree.to_string(),
        };
        let group: Vec<String> = p.group.iter().map(u64::to_string).collect();
        let _ = writeln!(
            s,
            "| `{dim}` | {} | {} | {:?} | {:?} | {degree} | {{{}}} | {:?} | {} |",
            inst.shape.dims[dim],
            sp.unit,
            sp.remainder,
            sp.scope,
            group.join(","),
            p.chosen,
            cells.join(" | ")
        );
    }
    let _ = writeln!(s, "\nEvery other dim is replicated on every rank.\n\n## Derived collectives per rank\n");
    let _ = writeln!(s, "| block | collective | group | {} | bytes a row |", head.join(" | "));
    let _ = writeln!(s, "|---|---|---|{}---:|", "---:|".repeat(head.len()));
    let mut rows: BTreeMap<(String, String, String), (Vec<u64>, u64)> = BTreeMap::new();
    for (r, c) in today.iter().enumerate() {
        for n in c.nodes.iter().filter(|n| matches!(n.op, OpKind::AllReduce | OpKind::AllGather | OpKind::Broadcast)) {
            let e = &c.edges[n.outputs[0]];
            let key = (n.block.clone(), n.op.name().to_string(), n.params.get("group").cloned().unwrap_or_default());
            let entry = rows.entry(key).or_insert_with(|| (vec![0; today.len()], e.format.bytes(1, e.dim_value).unwrap()));
            entry.0[r] += 1;
        }
    }
    for ((block, op, group), (counts, bytes)) in &rows {
        let counts: Vec<String> = counts.iter().map(u64::to_string).collect();
        let _ = writeln!(s, "| `{block}` | {op} | {{{group}}} | {} | {bytes} |", counts.join(" | "));
    }
    let (lk, basis) = link(inst);
    let bw = dram_gbps(inst);
    let _ = writeln!(
        s,
        "\n## Cost model (decode n=1)\n\nPer rank: main-section weight bytes / {bw} GB/s (kernels/DEVICES.toml) + each \
         collective at {} us + payload / {} GB/s ({basis}). Ranks wait for each other at every \
         collective (over its group), so the step is the sum over segments of the slowest rank in each, not \
         the slowest rank's whole-step total (crates/circuit/src/parallel_cost.rs). It ranks layouts and predicts no step time: a lower row is a \
         **candidate to measure**, not a change to the serve.\n",
        lk.latency_us, lk.gbps
    );
    let seg = segmented(&today, bw, lk).unwrap();
    let base = seg.step_us;
    let costs: Vec<String> = today
        .iter()
        .map(|c| {
            let rc = rank_cost(c, bw, lk).unwrap();
            format!("{:.1} + {:.1}", rc.weight_us, rc.comm_us)
        })
        .collect();
    let whole = today.iter().map(|c| rank_cost(c, bw, lk).unwrap().total_us()).fold(0.0f64, f64::max);
    let waits: Vec<String> = seg.wait_per_rank().iter().map(|w| format!("{w:.1}")).collect();
    let _ = writeln!(
        s,
        "Today: **{base:.1} us** over {} segments (weight + collectives per rank, as if it never waited: {}; \
         the slowest of those, {whole:.1} us, is the whole-step form). Each rank waits at collectives for \
         {} us.\n",
        seg.segments.len() + 1,
        costs.join(", "),
        waits.join(", ")
    );
    let _ = writeln!(s, "### Per-segment imbalance\n\nPer closing block: Σ over its segments of the slowest rank's work less the fastest's, and of each rank's wait.\n");
    let _ = writeln!(s, "| closes in | segments | Σ (max − min) us | {} |", head.iter().map(|h| format!("{h} waits us")).collect::<Vec<_>>().join(" | "));
    let _ = writeln!(s, "|---|---:|---:|{}", "---:|".repeat(head.len()));
    let mut by_block: BTreeMap<String, (usize, f64, Vec<f64>)> = BTreeMap::new();
    for sg in &seg.segments {
        let r0 = &today[sg.group[0]];
        let block = r0.nodes[r0.node(&sg.collective).unwrap()].block.clone();
        let e = by_block.entry(block).or_insert_with(|| (0, 0.0, vec![0.0; today.len()]));
        let (mx, mn) = sg.work_us.iter().fold((f64::MIN, f64::MAX), |(a, b), x| (a.max(*x), b.min(*x)));
        e.0 += 1;
        e.1 += mx - mn;
        for (&r, w) in sg.group.iter().zip(&sg.wait_us) {
            e.2[r] += w;
        }
    }
    for (block, (k, spread, w)) in &by_block {
        let w: Vec<String> = w.iter().map(|x| format!("{x:.1}")).collect();
        let _ = writeln!(s, "| `{block}` | {k} | {spread:.1} | {} |", w.join(" | "));
    }
    let tail: Vec<String> = seg.tail_us.iter().map(|x| format!("{x:.1}")).collect();
    let _ = writeln!(s, "\nAfter the last collective each rank works {} us.\n", tail.join(", "));
    let replicated: BTreeMap<String, Circuit> = parallel::parts(&spec)
        .filter(|p| d.degree[*p] > 1)
        .map(|p| {
            let mut degree = d.degree.clone();
            degree.insert(p.clone(), 1);
            let mut i = inst.clone();
            i.parallel = Some(Deployment { degree, ..d.clone() });
            (p.clone(), ranks(&i, &t).unwrap().swap_remove(0))
        })
        .collect();
    let parts_of = rotate::attribute(&today[0], &replicated).unwrap();
    let pr = rotate::price(&today, &parts_of, bw).unwrap();
    let _ = writeln!(
        s,
        "### `Remainder::Rotate` (priced, not built)\n\nEach segment's split parts rotate which rank takes which \
         slice, the offsets chosen per segment to minimise its slowest rank: Σ slowest work {:.1} us today, {:.1} us \
         rotated, **{:.1} us/step recoverable** (an upper bound: an offset per segment, ignoring that a state's \
         slicing must stay one across steps).\n\n| closes in | segments | improved | us saved |\n|---|---:|---:|---:|",
        pr.today_us,
        pr.rotated_us,
        pr.today_us - pr.rotated_us
    );
    for (block, (k, better, us)) in &pr.per_block {
        let _ = writeln!(s, "| `{block}` | {k} | {better} | {us:.1} |");
    }
    let _ = writeln!(s, "\n| change (one part) | model us | vs today |\n|---|---:|---:|");
    for part in parallel::parts(&spec) {
        let sp = &spec[part];
        let now = d.degree[part];
        for deg in sp.degree.min..=sp.degree.max.min(d.ranks) {
            if deg == now {
                continue;
            }
            let mut degree = d.degree.clone();
            degree.insert(part.clone(), deg);
            let mut i = inst.clone();
            i.parallel = Some(Deployment { degree, ..d.clone() });
            let cell = match ranks(&i, &t) {
                Ok(rs) => {
                    let us = step_us(&rs, bw, lk).unwrap();
                    format!("{us:.1} | {:+.2}%", (us / base - 1.0) * 100.0)
                }
                Err(e) => format!("refused | {e}"),
            };
            let _ = writeln!(s, "| `{part}` {now} -> {deg} | {cell} |");
        }
    }
    s
}

fn deployments() -> Vec<Instance> {
    common::instances().into_iter().filter(|i| i.parallel.is_some()).collect()
}

#[test]
fn the_layout_reports_are_current() {
    let insts = deployments();
    assert!(!insts.is_empty(), "the GLM TP=3 deployment is reported");
    for inst in insts {
        let rel = format!("{DIR}/{}.md", slug(&inst));
        let on_disk = std::fs::read_to_string(common::root().join(&rel)).unwrap_or_default();
        assert!(on_disk == report(&inst), "{rel} is stale; regenerate with `{COMMAND}`");
    }
}

#[test]
#[ignore = "writes kernels/circuits/plans/parallel/; run explicitly to regenerate"]
fn regenerate() {
    std::fs::create_dir_all(common::root().join(DIR)).unwrap();
    for inst in deployments() {
        std::fs::write(common::root().join(format!("{DIR}/{}.md", slug(&inst))), report(&inst)).unwrap();
    }
}

/// 2026-10-23: The model discriminates: replicating the routed experts (every rank reads all
/// 2048 columns) costs more weight time than today's three-way split, and splitting them saves
/// what it moves; a part with no collective of its own changes only the weight term.
#[test]
fn the_cost_model_prices_the_split_it_removes() {
    let inst = deployments().into_iter().find(|i| i.arch == "glm5_next").unwrap();
    let t = common::Texts::of(&inst);
    let (lk, _) = link(&inst);
    let bw = dram_gbps(&inst);
    let today = ranks(&inst, &t).unwrap();
    let mut i = inst.clone();
    let d = i.parallel.as_mut().unwrap();
    d.degree.insert("moe_inter".into(), 1);
    let whole = ranks(&i, &t).unwrap();
    let (a, b) = (rank_cost(&today[0], bw, lk).unwrap(), rank_cost(&whole[0], bw, lk).unwrap());
    assert!(b.weight_us > a.weight_us * 1.2, "replicated experts read more: {a:?} vs {b:?}");
    assert_eq!(a.collectives, b.collectives, "the MoE site still sums its shared expert's partial");
}
