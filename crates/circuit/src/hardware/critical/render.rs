//! 2026-10-23: The Markdown report of `met circuit whatif`.
//!
//! Owner: metrale-circuit (hardware).
//! Invariants: renders what [`super::analyze::analyze`] computed; computes nothing but
//! percentages and ranks of those numbers.

use crate::prelude::*;

use core::fmt::Write;

use super::analyze::WhatIf;
use super::backtest::{Breakpoint, Verdict};

fn pct(a: f64, b: f64) -> f64 {
    100.0 * (a - b) / b
}

fn us(x: Option<f64>) -> String {
    x.map_or_else(
        || "∞".into(),
        |x| format!("{:.1}", if x.abs() < 0.05 { 0.0 } else { x }),
    )
}

/// 2026-10-23: The report.
pub fn render_whatif(
    w: &WhatIf,
    verdicts: &[Verdict],
    bp: Option<&Breakpoint>,
    command: &str,
    top: usize,
) -> String {
    let mut o = String::new();
    let _ = writeln!(o, "# What-if: critical path of {}\n", w.source);
    let _ = writeln!(
        o,
        "Generated by `{command}`. Single capture, rank 0 only, n=1: collectives are fixed-duration nodes at their measured rank-0 duration (the other ranks are not captured), so every prediction assumes the other ranks change the same way.\n"
    );
    let _ = writeln!(
        o,
        "## Reproduction ({} steps, KV {:.0})\n",
        w.steps, w.kv_tokens
    );
    let _ = writeln!(o, "| model | step µs | vs measured |\n|---|---:|---:|");
    let _ = writeln!(
        o,
        "| measured (anchor to anchor) | {:.2} | |",
        w.measured_step_us
    );
    let _ = writeln!(
        o,
        "| replay (every edge its measured gap; consistency) | {:.2} | {:+.3}% |",
        w.replay_step_us,
        pct(w.replay_step_us, w.measured_step_us)
    );
    let _ = writeln!(
        o,
        "| max-plus: in-context work, one latency per edge kind | {:.2} | {:+.3}% |",
        w.model_step_us,
        pct(w.model_step_us, w.measured_step_us)
    );
    let _ = writeln!(
        o,
        "| simulation: + SM residency | {:.2} | {:+.3}% |",
        w.sim_sm_step_us,
        pct(w.sim_sm_step_us, w.measured_step_us)
    );
    let _ = writeln!(
        o,
        "| simulation: + SM residency + shared DRAM | {:.2} | {:+.3}% |",
        w.sim_step_us,
        pct(w.sim_step_us, w.measured_step_us)
    );
    for (k, s) in &w.without {
        let _ = writeln!(
            o,
            "| sabotage: max-plus without `{k}` edges | {:.2} | {:+.3}% |",
            s,
            pct(*s, w.measured_step_us)
        );
    }
    let _ = writeln!(
        o,
        "\nLatencies (median measured gap over the edges of the kind that bind their target): {}.",
        w.latency
            .iter()
            .map(|(k, v, n)| format!("{k} {v:.3} µs (n={n})"))
            .collect::<Vec<_>>()
            .join(", ")
    );
    if !w.dropped.is_empty() {
        let _ = writeln!(
            o,
            "Edges dropped for running backwards in measured time: {}.",
            w.dropped
                .iter()
                .map(|(k, n)| format!("{k} {n}"))
                .collect::<Vec<_>>()
                .join(", ")
        );
    }
    let d = &w.dram;
    let _ = writeln!(
        o,
        "Shared DRAM: {:.1} GB/s ({}; {} overlapped intervals, {:.0} µs; largest single kernel {:.1} GB/s; {} kernels' floor bytes clipped to the datasheet peak, {} reduced so the measured schedule fits the shared bandwidth).\n",
        d.bytes_per_us / 1e3,
        d.basis,
        d.overlapped_intervals,
        d.overlapped_us,
        d.solo_max_bytes_per_us / 1e3,
        d.clipped,
        d.scaled
    );
    let _ = writeln!(
        o,
        "## Critical chain\n\nPer step by edge kind: {}.\n",
        w.critical_by_kind
            .iter()
            .map(|(k, v)| format!("{k} {v:.1} µs"))
            .collect::<Vec<_>>()
            .join(", ")
    );
    let _ = writeln!(o, "Middle step, consecutive items merged (µs):\n");
    let line: Vec<String> = w
        .chain_step
        .iter()
        .filter(|c| c.us >= 0.5)
        .map(|c| format!("{} {:.1}", c.what, c.us))
        .collect();
    let _ = writeln!(o, "{}\n", line.join(" → "));
    let _ = writeln!(
        o,
        "## Sites: critical path vs Amdahl (top {top} by exact upside)\n"
    );
    let _ = writeln!(
        o,
        "| # | site | work µs | floor µs | critical µs | subgradient | slack min / median µs | Amdahl upside | exact (max-plus) | simulated | Amdahl rank |"
    );
    let _ = writeln!(o, "|---:|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|");
    let mut by_amdahl: Vec<(usize, f64)> = w
        .sites
        .iter()
        .enumerate()
        .map(|(i, s)| (i, s.amdahl_us.unwrap_or(0.0)))
        .collect();
    by_amdahl.sort_by(|a, b| b.1.total_cmp(&a.1));
    let arank = |i: usize| by_amdahl.iter().position(|x| x.0 == i).map_or(0, |p| p + 1);
    for (i, s) in w.sites.iter().enumerate().take(top) {
        let _ = writeln!(
            o,
            "| {} | {} · {} | {:.1} | {:.1} | {:.1} | {:.2} | {} / {} | {} | {:.1} | {:.1} | {} |",
            i + 1,
            s.run,
            s.site,
            s.work_us,
            s.floor_us,
            s.critical_us,
            s.subgradient,
            us(s.slack_min_us),
            us(s.slack_median_us),
            s.amdahl_us.map_or("–".into(), |a| format!("{a:.1}")),
            s.exact_us,
            s.sim_us,
            arank(i)
        );
    }
    let _ = writeln!(o, "\nAmdahl's top {top}, for comparison:\n");
    let _ = writeln!(
        o,
        "| Amdahl rank | site | Amdahl upside | exact (max-plus) | simulated | subgradient |\n|---:|---|---:|---:|---:|---:|"
    );
    for (r, &(i, a)) in by_amdahl.iter().take(top).enumerate() {
        let s = &w.sites[i];
        let _ = writeln!(
            o,
            "| {} | {} · {} | {a:.1} | {:.1} | {:.1} | {:.2} |",
            r + 1,
            s.run,
            s.site,
            s.exact_us,
            s.sim_us,
            s.subgradient
        );
    }
    if !w.rewrites.is_empty() {
        let _ = writeln!(
            o,
            "\n## Rewrites\n\n| set | places | max-plus Δ µs | simulated Δ µs | simulated Δ % |\n|---|---|---:|---:|---:|"
        );
        for r in &w.rewrites {
            let _ = writeln!(
                o,
                "| {} | {:?} | {:+.1} | {:+.1} | {:+.3}% |",
                r.id,
                r.places,
                r.maxplus_delta_us,
                r.sim_delta_us,
                100.0 * r.sim_delta_us / w.measured_step_us
            );
        }
        let _ = writeln!(
            o,
            "\nWhere each set moves the critical chain (max-plus, µs/step before → after):\n"
        );
        for r in &w.rewrites {
            let parts: Vec<String> = r
                .shifts
                .iter()
                .map(|(k, a, b)| format!("{k} {a:.1} → {b:.1}"))
                .collect();
            let _ = writeln!(o, "- {}: {}", r.id, parts.join("; "));
        }
    }
    if !verdicts.is_empty() {
        let _ = writeln!(
            o,
            "\n## Backtest (+ = step slower)\n\n| set | ledger | predicted µs (sim) | max-plus µs | measured µs [interval] | error % of step | sign | error ≤ 0.3% |\n|---|---|---:|---:|---|---:|---|---|"
        );
        for v in verdicts {
            let _ = writeln!(
                o,
                "| {} | {} | {:+.1} | {:+.1} | {:+.1} [{:+.1}, {:+.1}] | {:.3} | {} | {} |",
                v.id,
                v.depends_on.join(", "),
                v.predicted_us,
                v.maxplus_us,
                v.measured_us,
                v.lo,
                v.hi,
                v.error_pct,
                if v.sign_ok { "ok" } else { "WRONG" },
                if v.error_ok { "ok" } else { "no" }
            );
        }
        let _ = writeln!(
            o,
            "\nNothing was fitted on these outcomes (the latencies and the DRAM constant come from the capture alone), so leave-one-out does not apply. Measurement bases:\n"
        );
        for v in verdicts {
            let _ = writeln!(o, "- {}: {}", v.id, v.basis);
        }
    }
    if let Some(b) = bp {
        let _ = writeln!(o, "\n## KV breakpoint: {}\n", b.site);
        let _ = writeln!(
            o,
            "| KV | critical µs/step | subgradient | min slack µs | rank by critical time |\n|---:|---:|---:|---:|---:|"
        );
        for (k, (kv, c, sg, sl)) in b.at.iter().enumerate() {
            let _ = writeln!(
                o,
                "| {kv:.0} | {c:.1} | {sg:.2} | {} | {} |",
                us(*sl),
                b.rank.get(k).copied().unwrap_or(0)
            );
        }
        let _ = writeln!(
            o,
            "\nBecomes critical (slack changes sign): {}.",
            b.becomes_critical_kv.map_or(
                "no — same side of the chain at both KV lengths".into(),
                |k| format!("at KV ≈ {k:.0}")
            )
        );
        let _ = writeln!(o, "Overtakes (linear in KV between the two captures):\n");
        for c in &b.crossings {
            let _ = writeln!(
                o,
                "- {}: {}",
                c.other,
                c.kv.map_or("never (grows no faster)".into(), |k| format!("KV ≈ {k:.0}"))
            );
        }
    }
    o
}
