//! 2026-10-22: The Markdown of a headroom report (`met circuit headroom --format md`).
//!
//! Owner: metrale-circuit (hardware).
//! Invariants: deterministic text; a measured cell is printed only from a capture, an unmeasured
//! site reads `unmeasured` with its projection, and an energy cell without captured energy reads
//! `–`, never 0.

use crate::prelude::*;

use core::fmt::Write as _;

use super::headroom::{Headroom, Outside, SiteRow, Upside};
use super::stats::Interval;

/// 2026-10-22: Rows of the "top sites" table.
pub const TOP: usize = 10;

fn us(x: f64) -> String {
    format!("{:.2}", x + 0.0)
}

fn ms(x: f64) -> String {
    format!("{:.3}", x / 1e3 + 0.0)
}

fn opt(x: Option<f64>, f: fn(f64) -> String) -> String {
    x.map_or_else(|| "–".to_string(), f)
}

fn pct(x: f64) -> String {
    format!("{:.1}%", x + 0.0)
}

fn share(x: f64, of: Option<f64>) -> String {
    match of {
        Some(s) if s > 0.0 => pct(100.0 * x / s),
        _ => "–".into(),
    }
}

fn measured_cells(r: &SiteRow) -> (String, String) {
    match &r.measured {
        Some(m) => (us(m.total_us), us(m.exclusive_us)),
        None => (
            format!("unmeasured (projection {})", us(r.floor_us)),
            "–".into(),
        ),
    }
}

/// 2026-10-22: The report text; `command` is the line that regenerates it.
pub fn render_headroom(h: &Headroom, command: &str) -> String {
    let mut s = String::new();
    let _ = writeln!(
        s,
        "# Headroom: {} on {} ({})\n\nGenerated by `{command}`. Do not edit: the `--check` test fails on a stale copy.\n",
        h.model,
        h.device,
        h.runs.join(" + ")
    );
    if h.trace.is_none() {
        let _ = writeln!(
            s,
            "No capture: every site is unmeasured and shows its roofline projection; no upside, residual or measured step is computed.\n"
        );
    } else {
        let _ = writeln!(s, "**Uncertainty**: {}\n", h.uncertainty);
    }
    inputs(&mut s, h);
    budget(&mut s, h);
    plan_shares(&mut s, h);
    top(&mut s, h);
    cumulative(&mut s, h);
    outside(&mut s, h);
    all_sites(&mut s, h);
    cross_check(&mut s, h);
    drift(&mut s, h);
    s
}

/// 2026-10-23: Per run, the plan-describable and plan-executed shares of the step; nothing
/// without a capture.
fn plan_shares(s: &mut String, h: &Headroom) {
    if h.shares.is_empty() {
        return;
    }
    let _ = writeln!(
        s,
        "## Plan shares\n\nPlan-describable: the exclusive time of the launch sites the plan names. Plan-executed: the part of it the circuit executor issued from the plan in the captured serve (the capture's `[plan.execution]`); the rest ran on the model's own layer code.\n\n| run | executed by | describable us | describable share | executed us | executed share | why |\n|---|---|---:|---:|---:|---:|---|"
    );
    for r in &h.shares {
        let _ = writeln!(
            s,
            "| {} | {} | {} | {} | {} | {} | {} |",
            r.run,
            r.by.name(),
            us(r.describable_us),
            pct(r.describable_pct),
            us(r.executed_us),
            pct(r.executed_pct),
            r.why
        );
    }
    let (d, e): (f64, f64) = h.shares.iter().fold((0.0, 0.0), |(d, e), r| {
        (d + r.describable_us, e + r.executed_us)
    });
    let (dp, ep): (f64, f64) = h.shares.iter().fold((0.0, 0.0), |(d, e), r| {
        (d + r.describable_pct, e + r.executed_pct)
    });
    let _ = writeln!(
        s,
        "| **step** | – | {} | {} | {} | {} | – |\n",
        us(d),
        pct(dp),
        us(e),
        pct(ep)
    );
}

/// 2026-10-22: `x [lo, hi]` with `f`, or `x` alone without an interval.
fn with(x: f64, ci: Option<Interval>, f: fn(f64) -> String) -> String {
    match ci {
        Some(c) => format!("{} [{}, {}]", f(x), f(c.lo), f(c.hi)),
        None => f(x),
    }
}

fn one(x: f64) -> String {
    format!("{:.1}", x + 0.0)
}

fn inputs(s: &mut String, h: &Headroom) {
    let _ = writeln!(s, "## Inputs\n\n| | |\n|---|---|");
    let _ = writeln!(s, "| roofline | {} |", h.roofline);
    let _ = writeln!(s, "| step | {} |", h.runs.join(" + "));
    let _ = writeln!(
        s,
        "| KV context | {:.0} tokens per sequence ({}) |",
        h.kv_tokens.value, h.kv_tokens.basis
    );
    let _ = writeln!(
        s,
        "| tokens per step | {:.3} ({}) |",
        h.tokens_per_step.value, h.tokens_per_step.basis
    );
    let launch = h.launch_floor_us.as_ref().map_or_else(
        || "not stated: no site is classed launch-bound".to_string(),
        |l| format!("{} us per launch ({})", us(l.value), l.basis),
    );
    let _ = writeln!(s, "| launch floor | {launch} |");
    let dims = if h.dims.is_empty() {
        "the instance's".to_string()
    } else {
        let d: Vec<String> = h.dims.iter().map(|(k, v)| format!("{k}={v}")).collect();
        format!(
            "{} ({})",
            d.join(" "),
            h.dims_basis.as_deref().unwrap_or("no basis stated")
        )
    };
    let _ = writeln!(s, "| dims | {dims} |");
    let _ = writeln!(s, "| capture | {} |", h.trace.as_deref().unwrap_or("none"));
    let _ = writeln!(
        s,
        "| energy | {} |",
        h.energy.as_deref().unwrap_or(
            "no energy roofline stated for this class and no captured energy: energy columns are blank"
        )
    );
    let _ = writeln!(
        s,
        "| target | {}% of each site's floor (the second upside column) |\n",
        h.target_pct
    );
}

fn budget(s: &mut String, h: &Headroom) {
    let t = &h.totals;
    let step = t.step_us;
    let _ = writeln!(
        s,
        "## Step budget\n\nMicroseconds per step. Exclusive time is the part of a kernel no earlier-launched kernel overlaps; the residual is the time no kernel runs (host work, syncs, waits, launch gaps): measured step = sites + outside the plan + residual.\n\n| | us/step | 95% interval | share of step | tok/s |\n|---|---:|---:|---:|---:|"
    );
    let ci = t.ci.as_ref();
    let row =
        |s: &mut String, name: &str, v: Option<f64>, iv: Option<Interval>, tok: Option<String>| {
            let _ = writeln!(
                s,
                "| {name} | {} | {} | {} | {} |",
                opt(v, us),
                iv.map_or_else(|| "–".into(), |c| format!("[{}, {}]", us(c.lo), us(c.hi))),
                v.map_or_else(|| "–".into(), |v| share(v, step)),
                tok.unwrap_or_else(|| "–".into())
            );
        };
    row(
        s,
        "measured step",
        step,
        ci.map(|c| c.step_us),
        t.step_tok_s.map(|x| with(x, ci.map(|c| c.step_tok_s), one)),
    );
    row(
        s,
        "Σ launch sites, exclusive",
        t.sites_exclusive_us,
        None,
        None,
    );
    row(
        s,
        "Σ kernels outside the plan, exclusive",
        t.outside_exclusive_us,
        None,
        None,
    );
    row(
        s,
        "residual: no kernel running",
        t.residual_us,
        ci.map(|c| c.residual_us),
        None,
    );
    row(
        s,
        "overlap: two kernels at once (not added)",
        t.overlap_us,
        None,
        None,
    );
    row(
        s,
        "step ceiling: Σ site floors",
        Some(t.ceiling_us),
        None,
        Some(one(t.ceiling_tok_s)),
    );
    row(
        s,
        "of which measured sites' floors",
        t.measured_floor_us,
        None,
        None,
    );
    row(
        s,
        "of which unmeasured sites' projections",
        Some(t.unmeasured_projection_us),
        None,
        None,
    );
    let _ = writeln!(s);
}

fn top(s: &mut String, h: &Headroom) {
    let p = h.target_pct;
    let _ = writeln!(
        s,
        "## Top sites by upside\n\nEach row alone: the time the step saves, and its tok/s, if that site fell to its floor (100%) or to {p}% of it, every other site unchanged. A site saves at most its exclusive time. Brackets are 95% intervals; `≈` marks a site whose upside interval overlaps a neighbour's (their order is not resolved).\n\n| # | run | site | bound | floor us | measured us | % of floor | saved us @100% | tok/s @100% | saved us @{p}% | tok/s @{p}% | uJ/launch | % of E floor | E upside uJ |\n|---:|---|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"
    );
    for (i, r) in h
        .sites
        .iter()
        .filter(|r| r.upside_full.is_some_and(|u| u.saved_us > 0.0))
        .take(TOP)
        .enumerate()
    {
        let c = r.ci.as_ref();
        let m = r.measured.as_ref().map_or(0.0, |m| m.total_us);
        let cell = |u: Option<Upside>, sv: Option<Interval>, tk: Option<Interval>| {
            u.map_or_else(
                || ("–".to_string(), "–".to_string()),
                |u| (with(u.saved_us, sv, us), with(u.tok_s, tk, one)),
            )
        };
        let (s1, t1) = cell(
            r.upside_full,
            c.map(|c| c.saved_full_us),
            c.map(|c| c.tok_s_full),
        );
        let (s2, t2) = cell(
            r.upside_target,
            c.map(|c| c.saved_target_us),
            c.map(|c| c.tok_s_target),
        );
        let _ = writeln!(
            s,
            "| {}{} | {} | {} | {} | {} | {} | {} | {s1} | {t1} | {s2} | {t2} | {} | {} | {} |",
            i + 1,
            if r.tied { " ≈" } else { "" },
            r.run,
            r.site,
            r.bound.name(),
            us(r.floor_us),
            with(m, c.map(|c| c.total_us), us),
            r.pct_of_floor
                .map_or_else(|| "–".into(), |x| with(x, c.map(|c| c.pct_of_floor), pct)),
            opt(r.energy.uj_per_launch, us),
            opt(r.energy.pct_of_floor, pct),
            opt(r.energy.upside_uj, us),
        );
    }
    let _ = writeln!(s);
}

fn cross_check(s: &mut String, h: &Headroom) {
    let Some(t) = h.totals.ci.as_ref() else {
        return;
    };
    let _ = writeln!(
        s,
        "## Cross-check: bootstrap and delta method\n\nThe same 95% intervals by the moving-block bootstrap and by the delta method (Newey-West variance of the mean). Agreement says the bootstrap is not an artefact of its resampling; a delta interval much narrower than the bootstrap's means the statistic is far from linear in the mean there.\n\n| quantity | bootstrap | delta method |\n|---|---:|---:|"
    );
    let iv = |c: Interval, f: fn(f64) -> String| format!("[{}, {}]", f(c.lo), f(c.hi));
    let _ = writeln!(
        s,
        "| residual us | {} | {} |",
        iv(t.residual_us, us),
        iv(t.residual_delta, us)
    );
    for r in h
        .sites
        .iter()
        .filter(|r| r.upside_full.is_some_and(|u| u.saved_us > 0.0))
        .take(TOP)
    {
        if let Some(c) = &r.ci {
            let _ = writeln!(
                s,
                "| % of floor, {} · {} | {} | {} |",
                r.run,
                r.site,
                iv(c.pct_of_floor, pct),
                iv(c.pct_of_floor_delta, pct)
            );
        }
    }
    let _ = writeln!(s);
}

fn cumulative(s: &mut String, h: &Headroom) {
    if h.curve.is_empty() {
        return;
    }
    let p = h.target_pct;
    let _ = writeln!(
        s,
        "## Cumulative: the top N sites to their floor\n\n| N | adds | saved us @100% | step ms @100% | tok/s @100% | saved us @{p}% | step ms @{p}% | tok/s @{p}% |\n|---:|---|---:|---:|---:|---:|---:|---:|"
    );
    for c in &h.curve {
        let _ = writeln!(
            s,
            "| {} | {} | {} | {} | {:.1} | {} | {} | {:.1} |",
            c.n,
            c.site,
            us(c.full.saved_us),
            ms(c.full.step_us),
            c.full.tok_s,
            us(c.target.saved_us),
            ms(c.target.step_us),
            c.target.tok_s
        );
    }
    let _ = writeln!(s);
}

fn outside(s: &mut String, h: &Headroom) {
    if h.trace.is_none() {
        return;
    }
    let _ = writeln!(
        s,
        "## Kernels outside the plan\n\nCaptured kernels no launch site of the step runs (another lowering than the plan's, a library kernel, or a launch the capture did not attribute). Their time is in the budget above, never dropped.\n\n| kernel | label | calls/step | us/step | exclusive us/step | why |\n|---|---|---:|---:|---:|---|"
    );
    for o in &h.outside {
        let why = match &o.why {
            Outside::Unknown => "no launch site runs it".to_string(),
            Outside::Ambiguous(sites) => format!("several sites run it: {}", sites.join("; ")),
        };
        let _ = writeln!(
            s,
            "| `{}` | {} | {:.2} | {} | {} | {why} |",
            o.kernel,
            o.label.as_deref().unwrap_or("–"),
            o.calls_per_step,
            us(o.total_us),
            us(o.exclusive_us)
        );
    }
    let _ = writeln!(s);
}

fn all_sites(s: &mut String, h: &Headroom) {
    let _ = writeln!(
        s,
        "## Every launch site\n\nA % of floor above 100 means the capture's lowering moved work out of the site (see Plan vs capture): its floor is the plan's, not this lowering's, and it has no upside.

`fused`: the floor drops the edges the plan fuses inside the launch; `node sum` is the hardware report's per-node estimate of the same nodes with every edge counted (their difference is the fusion's modelled gain).\n\n| run | site | kernels | groups | launches | MB | GFLOP | bound | floor us | node sum us | fused | measured us | exclusive us | % of floor |\n|---|---|---|---:|---:|---:|---:|---|---:|---:|---|---:|---:|---:|"
    );
    for r in &h.sites {
        let (m, x) = measured_cells(r);
        let _ = writeln!(
            s,
            "| {} | {} | {} | {} | {} | {:.3} | {:.3} | {} | {} | {} | {} | {m} | {x} | {} |",
            r.run,
            r.site,
            r.kernels,
            r.groups,
            r.launches,
            r.bytes / 1e6 + 0.0,
            r.flops / 1e9 + 0.0,
            r.bound.name(),
            us(r.floor_us),
            us(r.node_sum_us),
            if r.fused { "yes" } else { "no" },
            opt(r.pct_of_floor, pct)
        );
    }
    let _ = writeln!(s);
}

fn drift(s: &mut String, h: &Headroom) {
    let notes: Vec<String> = h
        .sites
        .iter()
        .filter_map(|r| r.measured.as_ref().map(|m| (r, m)))
        .flat_map(|(r, m)| {
            m.drift
                .iter()
                .map(move |d| format!("- {} · {}: {d}", r.run, r.site))
        })
        .collect();
    if notes.is_empty() {
        return;
    }
    let _ = writeln!(
        s,
        "## Plan vs capture\n\nThe capture's lowering differs from the plan's at these sites (another kernel or family, or a neighbouring site's work folded in, as the exporter's attribution notes); the floor stays the plan's, so a site that took on other sites' work can read below its floor's share and the sites that gave it up read unmeasured.\n\n{}\n",
        notes.join("\n")
    );
}
