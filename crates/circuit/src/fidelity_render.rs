//! 2026-10-23: The plan-fidelity report: per (trace, run, rank) the plan's launches against the
//! traced segment's, the multiset and order scores, the residual kernels, and what the step
//! launches that no run plans.
//!
//! Owner: metrale-circuit.
//! Invariants:
//! - A rank without a capture is scored against nothing and says so ("code-derived"); its plan's
//!   difference from the captured rank's plan is listed instead, never a score borrowed from
//!   another rank.
//! - A run's score over a trace is the step-weighted mean over the trace's variants.

use crate::prelude::*;

use alloc::collections::BTreeMap;
use core::fmt::Write as _;

use super::{Fidelity, Trace, compare, plan_sequence};
use crate::fuser::FusionPlan;
use crate::venn::Run;

/// 2026-10-23: One rank's plan at one run.
#[derive(Debug, Clone)]
pub struct RankPlan<'a> {
    /// 2026-10-23: The rank.
    pub rank: u64,
    /// 2026-10-23: The run.
    pub run: Run,
    /// 2026-10-23: Its plan.
    pub plan: &'a FusionPlan,
}

/// 2026-10-23: `plan` against each variant of `t` that has a segment at `run`: (variant, steps,
/// score).
pub fn score(plan: &FusionPlan, t: &Trace, run: Run) -> Vec<(String, u64, Fidelity)> {
    t.variant
        .iter()
        .filter_map(|v| {
            v.segment
                .iter()
                .find(|s| s.mode.as_deref() == Some(run.mode.name()) && s.rows == Some(run.rows))
                .map(|s| (v.name.clone(), v.steps, compare(plan, &s.kernels)))
        })
        .collect()
}

fn weighted(xs: &[(String, u64, Fidelity)], f: impl Fn(&Fidelity) -> f64) -> f64 {
    let steps: u64 = xs.iter().map(|x| x.1).sum();
    if steps == 0 {
        return 0.0;
    }
    xs.iter().map(|x| f(&x.2) * x.1 as f64).sum::<f64>() / steps as f64
}

fn pct(x: f64) -> String {
    format!("{:.1}%", x * 100.0)
}

fn list(m: &BTreeMap<String, u64>) -> String {
    if m.is_empty() {
        return "none".into();
    }
    m.iter()
        .map(|(k, n)| format!("`{k}` x{n}"))
        .collect::<Vec<_>>()
        .join(", ")
}

/// 2026-10-23: The multiset difference of two plans' launches: (only in `a`, only in `b`).
fn plan_diff(a: &FusionPlan, b: &FusionPlan) -> (BTreeMap<String, u64>, BTreeMap<String, u64>) {
    let count = |p: &FusionPlan| {
        let mut m: BTreeMap<String, i64> = BTreeMap::new();
        for k in plan_sequence(p).0 {
            *m.entry(k).or_insert(0) += 1;
        }
        m
    };
    let (ca, cb) = (count(a), count(b));
    let (mut only_a, mut only_b) = (BTreeMap::new(), BTreeMap::new());
    for k in ca.keys().chain(cb.keys()) {
        let d = ca.get(k).copied().unwrap_or(0) - cb.get(k).copied().unwrap_or(0);
        if d > 0 {
            only_a.insert(k.clone(), d.unsigned_abs());
        } else if d < 0 {
            only_b.insert(k.clone(), d.unsigned_abs());
        }
    }
    (only_a, only_b)
}

/// 2026-10-23: The report. `traces` are (file, oracle); `plans` every rank at every run.
pub fn render(
    title: &str,
    command: &str,
    traces: &[(String, Trace)],
    plans: &[RankPlan<'_>],
) -> String {
    let mut s = String::new();
    let _ = writeln!(
        s,
        "# Plan fidelity: {title}\n\nGenerated by `{command}`. Do not edit: the check test fails on a \
         stale copy.\n\nEach rank's fused plan (its own TP dims) against the launches an nsys capture \
         of the serve made at the same run. **fidelity** = multiset Jaccard (matched / (planned + traced \
         - matched)); **order** = longest common subsequence / the longer sequence; both step-weighted \
         over the capture's step variants. A placeholder group (`novel`) launches nothing, so a site \
         the plan cannot describe costs fidelity by what the serve ran there.\n"
    );
    let _ = writeln!(s, "## Captures\n");
    for (file, t) in traces {
        let variants: Vec<String> = t
            .variant
            .iter()
            .map(|v| format!("{} x{}", v.name, v.steps))
            .collect();
        let _ = writeln!(
            s,
            "- `{file}`: rank {}, {} steps (variants {}); sqlite sha256 `{}`. {}",
            t.rank,
            t.steps,
            variants.join(", "),
            t.sqlite_sha256.get(..16).unwrap_or(&t.sqlite_sha256),
            t.source
        );
    }
    let _ = writeln!(
        s,
        "\n## Scores\n\n| run | rank | capture | planned | traced | matched | fidelity | order | novel |\n\
         |---|---:|---|---:|---:|---:|---:|---:|---:|"
    );
    let mut residuals = String::new();
    for p in plans {
        let (seq, novel) = plan_sequence(p.plan);
        let captured: Vec<&(String, Trace)> = traces.iter().filter(|(_, t)| t.rank == p.rank).collect();
        let mut scored_any = false;
        for (file, t) in &captured {
            let xs = score(p.plan, t, p.run);
            let Some((_, _, top)) = xs.first() else {
                continue;
            };
            scored_any = true;
            let _ = writeln!(
                s,
                "| {} n={} | {} | `{}` | {} | {} | {} | {} | {} | {} |",
                p.run.mode.name(),
                p.run.rows,
                p.rank,
                file,
                top.planned,
                top.traced,
                top.matched,
                pct(weighted(&xs, Fidelity::share)),
                pct(weighted(&xs, Fidelity::order_share)),
                novel.len()
            );
            let _ = writeln!(
                residuals,
                "- {} n={} rank {} vs `{file}` (variant {}): traced, not planned: {}; planned, not \
                 traced: {}; placeholders: {}",
                p.run.mode.name(),
                p.run.rows,
                p.rank,
                xs[0].0,
                list(&top.missing),
                list(&top.extra),
                if novel.is_empty() { "none".into() } else { novel.join(", ") }
            );
        }
        if !scored_any {
            let why = if traces.iter().any(|(_, t)| !score(p.plan, t, p.run).is_empty()) {
                "no capture of this rank (code-derived)"
            } else {
                "no capture of this run"
            };
            let _ = writeln!(
                s,
                "| {} n={} | {} | {why} | {} | - | - | - | - | {} |",
                p.run.mode.name(),
                p.run.rows,
                p.rank,
                seq.len(),
                novel.len()
            );
            let base = plans
                .iter()
                .find(|q| q.run == p.run && traces.iter().any(|(_, t)| t.rank == q.rank));
            if let Some(b) = base.filter(|b| b.rank != p.rank) {
                let (only_here, only_there) = plan_diff(p.plan, b.plan);
                let _ = writeln!(
                    residuals,
                    "- {} n={} rank {} (code-derived) vs rank {}'s plan: only here: {}; only on rank \
                     {}: {}; placeholders: {}",
                    p.run.mode.name(),
                    p.run.rows,
                    p.rank,
                    b.rank,
                    list(&only_here),
                    b.rank,
                    list(&only_there),
                    if novel.is_empty() { "none".into() } else { novel.join(", ") }
                );
            }
        }
    }
    let _ = writeln!(s, "\n## Residuals\n\n{residuals}");
    let _ = writeln!(s, "## Launched, planned by no run\n");
    for (file, t) in traces {
        for v in &t.variant {
            for seg in v.segment.iter().filter(|g| g.mode.is_none()) {
                let mut m = BTreeMap::new();
                for k in &seg.kernels {
                    *m.entry(k.clone()).or_insert(0u64) += 1;
                }
                let _ = writeln!(
                    s,
                    "- `{file}` variant {} ({} steps), {}: {}",
                    v.name,
                    v.steps,
                    seg.name,
                    list(&m)
                );
            }
        }
    }
    s
}
