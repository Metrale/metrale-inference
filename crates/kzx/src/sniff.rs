//! Content sniffing: pick the model profile from the first bytes. PTX text announces itself
//! with the NVVM banner or `.version`/`.target` directives, ELF (cubin, HIP code object) with
//! its magic; other mostly-printable input takes the text model, the rest the generic one.

use crate::format::Profile;

/// How many leading bytes sniffing inspects.
const WINDOW: usize = 4096;

fn contains(hay: &[u8], needle: &[u8]) -> bool {
    needle.is_empty() || hay.windows(needle.len()).any(|w| w == needle)
}

/// The profile [`crate::compress`] picks for `data`.
pub fn sniff(data: &[u8]) -> Profile {
    let head = &data[..data.len().min(WINDOW)];
    if head.starts_with(&[0x7f, b'E', b'L', b'F']) {
        return Profile::Elf;
    }
    if contains(head, b"NVVM Compiler") || (contains(head, b"\n.version ") && contains(head, b"\n.target ")) {
        return Profile::Ptx;
    }
    if head.is_empty() {
        return Profile::Generic;
    }
    let printable = head
        .iter()
        .filter(|&&b| b.is_ascii_graphic() || matches!(b, b' ' | b'\t' | b'\n' | b'\r'))
        .count();
    if printable * 100 >= head.len() * 95 {
        Profile::Ptx
    } else {
        Profile::Generic
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn recognises_each_class() {
        assert_eq!(sniff(b"\x7fELF\x02\x01\x01\x33\0\0\0\0\0\0\0\0"), Profile::Elf);
        assert_eq!(sniff(b"//\n// Generated by NVIDIA NVVM Compiler\n//\n"), Profile::Ptx);
        assert_eq!(sniff(b"// hello\n.version 9.0\n.target sm_90a\n.address_size 64\n"), Profile::Ptx);
        assert_eq!(sniff(b"plain words and\tlines\n"), Profile::Ptx);
        assert_eq!(sniff(&[0u8, 1, 2, 3, 255, 254, 7, 9]), Profile::Generic);
        assert_eq!(sniff(b""), Profile::Generic);
    }
}
