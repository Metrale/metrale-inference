//! A synthetic, public corpus with the *shape* of the real content classes: PTX-like text with
//! sequential register numbering and unrolled repeats, an ELF-like object with 128-bit
//! structured instruction words, a postcard-like body of strings, varints and hashes, and a
//! `.kbp`-like container around them. Everything is generated from a seed by templates written
//! here; nothing is copied from any compiled kernel.

#![allow(dead_code)]

/// xorshift64*: small, seedable, deterministic.
pub struct Rng(pub u64);

impl Rng {
    pub fn new(seed: u64) -> Self {
        Self(seed.max(1))
    }
    pub fn next(&mut self) -> u64 {
        self.0 ^= self.0 >> 12;
        self.0 ^= self.0 << 25;
        self.0 ^= self.0 >> 27;
        self.0.wrapping_mul(0x2545_F491_4F6C_DD1D)
    }
    pub fn below(&mut self, n: u64) -> u64 {
        self.next() % n.max(1)
    }
    pub fn pick<'a, T>(&mut self, items: &'a [T]) -> &'a T {
        &items[self.below(items.len() as u64) as usize]
    }
    pub fn bytes(&mut self, n: usize) -> Vec<u8> {
        (0..n).map(|_| (self.next() >> 24) as u8).collect()
    }
}

const OPS2: [&str; 10] = [
    "add.s32",
    "mul.lo.s32",
    "and.b32",
    "or.b32",
    "shl.b32",
    "shr.u32",
    "sub.s32",
    "min.s32",
    "max.s32",
    "xor.b32",
];
const OPSF: [&str; 8] = [
    "add.rn.f32",
    "mul.rn.f32",
    "fma.rn.f32",
    "max.f32",
    "min.f32",
    "sub.rn.f32",
    "ex2.approx.f32",
    "rcp.approx.f32",
];

/// One PTX-like module with `entries` kernels and about `lines_per_entry` instructions each.
pub fn ptx_module(rng: &mut Rng, index: usize, entries: usize, lines_per_entry: usize) -> Vec<u8> {
    let mut s = String::new();
    s.push_str("//\n// Generated by a synthetic PTX writer (kzx bench)\n//\n\n");
    s.push_str(".version 9.0\n.target sm_90a\n.address_size 64\n\n");
    for e in 0..entries {
        let name = format!("synth_kernel_{index}_{e}");
        s.push_str(&format!("\t// .globl\t{name}\n\n.visible .entry {name}(\n"));
        let nparams = 2 + rng.below(6) as usize;
        for p in 0..nparams {
            let ty = if p < nparams - 1 {
                ".u64 .ptr .align 1 "
            } else {
                ".u32 "
            };
            let sep = if p + 1 < nparams { "," } else { "" };
            s.push_str(&format!("\t.param {ty}{name}_param_{p}{sep}\n"));
        }
        s.push_str(")\n{\n");
        let (mut r, mut f, mut rd, mut p) = (1u32, 1u32, 1u32, 1u32);
        let regs = format!(
            "\t.reg .pred \t%p<{}>;\n\t.reg .b32 \t%r<{}>;\n\t.reg .b32 \t%f<{}>;\n\t.reg .b64 \t%rd<{}>;\n",
            lines_per_entry / 8 + 2,
            lines_per_entry + 8,
            lines_per_entry + 8,
            lines_per_entry / 4 + 4
        );
        s.push_str(&regs);
        s.push_str(&format!(
            "\t.shared .align 4 .b8 _ZZ{}{}E5s_val[4096];\n",
            name.len(),
            name
        ));
        for q in 0..nparams {
            s.push_str(&format!("\tld.param.u64 \t%rd{rd}, [{name}_param_{q}];\n"));
            rd += 1;
        }
        s.push_str(&format!(
            "\tmov.u32 \t%r{r}, %tid.x;\n\tmov.u32 \t%r{}, %ctaid.x;\n",
            r + 1
        ));
        r += 2;
        let mut block = 0;
        let unroll = 4 + rng.below(8) as usize;
        let mut body: Vec<String> = Vec::new();
        for _ in 0..unroll {
            body.push(match rng.below(6) {
                0 => format!("\t{} \t%r{{r}}, %r{{ra}}, %r{{rb}};\n", rng.pick(&OPS2)),
                1 => format!("\t{} \t%f{{f}}, %f{{fa}}, %f{{fb}};\n", rng.pick(&OPSF)),
                2 => format!(
                    "\tld.global.f32 \t%f{{f}}, [%rd{{rd}}+{}];\n",
                    rng.below(64) * 4
                ),
                3 => format!(
                    "\tst.shared.f32 \t[%r{{ra}}+{}], %f{{fa}};\n",
                    rng.below(32) * 128
                ),
                4 => "\tshfl.sync.down.b32\t%r{r}|%p{p}, %r{ra}, 16, 31, -1;\n".to_string(),
                _ => "\tmov.b32 \t%r{r}, %f{fa};\n".to_string(),
            });
        }
        let mut n = 0;
        while n < lines_per_entry {
            for t in &body {
                let line = t
                    .replace("{r}", &r.to_string())
                    .replace("{ra}", &(r.saturating_sub(1).max(1)).to_string())
                    .replace(
                        "{rb}",
                        &(r.saturating_sub(2 + rng.below(3) as u32).max(1)).to_string(),
                    )
                    .replace("{f}", &f.to_string())
                    .replace("{fa}", &(f.saturating_sub(1).max(1)).to_string())
                    .replace(
                        "{fb}",
                        &(f.saturating_sub(1 + rng.below(4) as u32).max(1)).to_string(),
                    )
                    .replace("{rd}", &(1 + rng.below(rd as u64) as u32).to_string())
                    .replace("{p}", &p.to_string());
                s.push_str(&line);
                r += 1;
                f += 1;
                n += 1;
            }
            if n % 16 == 0 {
                s.push_str(&format!("\tsetp.ne.s32 \t%p{p}, %r{}, 0;\n\tbar.sync \t0;\n\t@%p{p} bra \t$L__BB{e}_{block};\n$L__BB{e}_{block}:\n", r - 1));
                p += 1;
                block += 1;
            }
        }
        s.push_str(&format!(
            "\tst.global.f32 \t[%rd{}], %f{};\n\tret;\n\n}}\n",
            rd - 1,
            f - 1
        ));
    }
    s.into_bytes()
}

fn put_u16(v: &mut Vec<u8>, x: u16) {
    v.extend_from_slice(&x.to_le_bytes());
}
fn put_u32(v: &mut Vec<u8>, x: u32) {
    v.extend_from_slice(&x.to_le_bytes());
}
fn put_u64(v: &mut Vec<u8>, x: u64) {
    v.extend_from_slice(&x.to_le_bytes());
}

/// An ELF-like object: a 64-byte header, a `.text` of `words` 128-bit instruction words with
/// opcode, register, immediate and control fields, a string table and a symbol table.
pub fn elf_object(rng: &mut Rng, words: usize, symbols: usize) -> Vec<u8> {
    let mut v = Vec::new();
    v.extend_from_slice(&[
        0x7f, b'E', b'L', b'F', 2, 1, 1, 0x33, 0, 0, 0, 0, 0, 0, 0, 0,
    ]);
    put_u16(&mut v, 2);
    put_u16(&mut v, 190);
    put_u32(&mut v, 1);
    put_u64(&mut v, 0);
    put_u64(&mut v, 0);
    put_u64(&mut v, 64);
    put_u32(&mut v, 0x79_0000);
    put_u16(&mut v, 64);
    put_u16(&mut v, 0);
    put_u16(&mut v, 0);
    put_u16(&mut v, 64);
    put_u16(&mut v, 6);
    put_u16(&mut v, 1);
    let opcodes: Vec<u16> = (0..40).map(|_| (rng.next() & 0x3ff) as u16).collect();
    let mut body: Vec<[u8; 16]> = Vec::new();
    let loop_len = 6 + rng.below(10) as usize;
    let mut dst = 1u8;
    for _ in 0..loop_len {
        let mut w = [0u8; 16];
        let op = *rng.pick(&opcodes);
        w[0] = (op & 0xff) as u8;
        w[1] = (op >> 8) as u8 | ((rng.next() & 0x30) as u8);
        w[2] = dst;
        w[3] = dst.wrapping_sub(1 + (rng.next() & 3) as u8);
        w[4] = (rng.next() & 0x3f) as u8;
        w[5] = 0;
        let imm = (rng.below(4096) as u32) << 2;
        w[6..10].copy_from_slice(&imm.to_le_bytes());
        w[10] = 0;
        w[11] = 0;
        w[12] = (rng.next() & 0x1f) as u8;
        w[13] = 0x7c | (rng.next() & 3) as u8;
        w[14] = (rng.next() & 0x0f) as u8;
        w[15] = 0x0e;
        body.push(w);
        dst = dst.wrapping_add(1);
    }
    let mut n = 0;
    while n < words {
        for w in &body {
            let mut x = *w;
            x[2] = x[2].wrapping_add(((n / loop_len) as u8).wrapping_mul(2));
            x[3] = x[3].wrapping_add(((n / loop_len) as u8).wrapping_mul(2));
            if rng.below(16) == 0 {
                x[6] = x[6].wrapping_add(4);
            }
            v.extend_from_slice(&x);
            n += 1;
        }
    }
    let mut strtab = vec![0u8];
    let mut symtab = Vec::new();
    for i in 0..symbols {
        let off = strtab.len() as u32;
        strtab.extend_from_slice(format!("_Z12synth_sym_{i}PfS_j").as_bytes());
        strtab.push(0);
        put_u32(&mut symtab, off);
        symtab.push(0x12);
        symtab.push(0);
        put_u16(&mut symtab, 3);
        put_u64(&mut symtab, (i as u64) * 128);
        put_u64(&mut symtab, 128);
    }
    v.extend_from_slice(&strtab);
    while v.len() % 8 != 0 {
        v.push(0);
    }
    v.extend_from_slice(&symtab);
    v
}

/// Postcard wire helpers: LEB128 varints and length-prefixed strings.
pub fn varint(v: &mut Vec<u8>, mut x: u64) {
    while x >= 0x80 {
        v.push((x as u8) | 0x80);
        x >>= 7;
    }
    v.push(x as u8);
}
pub fn string(v: &mut Vec<u8>, s: &str) {
    varint(v, s.len() as u64);
    v.extend_from_slice(s.as_bytes());
}

/// A postcard-like blueprint body: names, a lever map, kernel specs with 32-byte hashes and a
/// node list, about `nodes * 60 + levers * 40` bytes.
pub fn postcard_body(rng: &mut Rng, nodes: usize, levers: usize, kernels: usize) -> Vec<u8> {
    let mut v = Vec::new();
    varint(&mut v, 1);
    v.extend_from_slice(&rng.bytes(32));
    varint(&mut v, 7);
    string(&mut v, "synthetic-blueprint-tp3-512k");
    string(&mut v, "org/synthetic-checkpoint");
    string(&mut v, "9e0d74e3c1a0b2f4d5e6f7a8b9c0d1e2f3a4b5c6");
    varint(&mut v, nodes as u64);
    let ops = [
        "norm", "q", "k", "v", "o", "gate_up", "down", "act", "residual",
    ];
    for n in 0..nodes {
        let layer = n / 9;
        let op = ops[n % 9];
        string(&mut v, &format!("l{layer}.blk.{op}"));
        string(&mut v, op);
        varint(&mut v, (n % 9) as u64);
        varint(&mut v, 1);
        varint(&mut v, n.saturating_sub(1) as u64);
        varint(&mut v, 1);
        varint(&mut v, n as u64 + 1);
        varint(&mut v, 2);
        string(&mut v, "k");
        string(&mut v, "5120");
        string(&mut v, "n");
        string(&mut v, &format!("{}", 1024 * (1 + rng.below(8))));
        varint(&mut v, layer as u64);
    }
    varint(&mut v, levers as u64);
    for l in 0..levers {
        string(
            &mut v,
            &format!(
                "SYNTH_LEVER_{}_{l}",
                ["KV", "SSM", "GDN", "MTP", "COMM"][l % 5]
            ),
        );
        match rng.below(4) {
            0 => {
                varint(&mut v, 0);
                v.push((rng.next() & 1) as u8);
            }
            1 => {
                varint(&mut v, 2);
                varint(&mut v, rng.below(4096));
            }
            2 => {
                varint(&mut v, 3);
                varint(&mut v, rng.below(100) * 2);
                v.push(0xfe);
            }
            _ => {
                varint(&mut v, 4);
                string(
                    &mut v,
                    ["auto", "bf16", "fp8", "200:50"][rng.below(4) as usize],
                );
            }
        }
    }
    varint(&mut v, kernels as u64);
    for k in 0..kernels {
        string(&mut v, &format!("synth_mod_{}", k / 4));
        string(&mut v, &format!("synth_kernel_{}_{}", k / 4, k % 4));
        string(&mut v, "sm_90a");
        varint(&mut v, 0);
        varint(&mut v, 4 + rng.below(8));
        varint(&mut v, rng.below(96) * 1024);
        varint(&mut v, 128 * (1 + rng.below(4)));
        v.extend_from_slice(&rng.bytes(32));
        v.extend_from_slice(&rng.bytes(32));
    }
    v
}

/// A `.kbp`-like container: 72-byte header, body, locator table, inline payload of the given
/// modules, signature block of random bytes.
pub fn kbp_container(rng: &mut Rng, body: &[u8], modules: &[Vec<u8>]) -> Vec<u8> {
    let mut payload = Vec::new();
    let mut locator = Vec::new();
    varint(&mut locator, modules.len() as u64);
    for m in modules {
        varint(&mut locator, 0);
        varint(&mut locator, payload.len() as u64);
        payload.extend_from_slice(&rng.bytes(32));
        put_u64(&mut payload, m.len() as u64);
        payload.extend_from_slice(m);
    }
    let mut sig = Vec::new();
    varint(&mut sig, 1);
    string(&mut sig, "kbp-blueprints-2026-10");
    let chain = rng.bytes(2048);
    varint(&mut sig, chain.len() as u64);
    sig.extend_from_slice(&chain);
    let a = rng.bytes(3309);
    varint(&mut sig, a.len() as u64);
    sig.extend_from_slice(&a);
    let b = rng.bytes(64);
    varint(&mut sig, b.len() as u64);
    sig.extend_from_slice(&b);
    let mut v = Vec::new();
    v.extend_from_slice(b"MKBP");
    put_u16(&mut v, 1);
    put_u16(&mut v, 1);
    put_u64(&mut v, body.len() as u64);
    v.extend_from_slice(&rng.bytes(32));
    put_u64(&mut v, locator.len() as u64);
    put_u64(&mut v, payload.len() as u64);
    put_u64(&mut v, sig.len() as u64);
    v.extend_from_slice(body);
    v.extend_from_slice(&locator);
    v.extend_from_slice(&payload);
    v.extend_from_slice(&sig);
    v
}

/// The synthetic corpus: `(class, files)`.
pub fn corpus(seed: u64, scale: usize) -> Vec<(&'static str, Vec<Vec<u8>>)> {
    let mut rng = Rng::new(seed);
    let mut ptx = Vec::new();
    for i in 0..scale * 4 {
        let (entries, lines) = (1 + rng.below(4) as usize, 200 + rng.below(1800) as usize);
        ptx.push(ptx_module(&mut rng, i, entries, lines));
    }
    let mut cubin = Vec::new();
    for _ in 0..scale * 4 {
        let (words, symbols) = (500 + rng.below(6000) as usize, 4 + rng.below(20) as usize);
        cubin.push(elf_object(&mut rng, words, symbols));
    }
    let mut body = Vec::new();
    for _ in 0..3 {
        let (n, l, k) = (
            1200 + rng.below(600) as usize,
            600 + rng.below(300) as usize,
            400 + rng.below(300) as usize,
        );
        body.push(postcard_body(&mut rng, n, l, k));
    }
    let kbp = vec![kbp_container(&mut rng, &body[0], &ptx)];
    vec![("ptx", ptx), ("cubin", cubin), ("body", body), ("kbp", kbp)]
}
