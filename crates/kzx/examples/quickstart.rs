//! Compress a PTX-like text, inspect the stream, and decompress it under explicit caps.
//! Run with `cargo run --example quickstart`.

fn main() {
    let raw: &[u8] = b"//\n// Generated by a tiny example\n//\n.version 9.0\n.target sm_90a\n.address_size 64\n\
.visible .entry demo_kernel(\n\t.param .u64 .ptr .align 1 demo_kernel_param_0\n)\n{\n\
\t.reg .b32 \t%r<8>;\n\t.reg .b64 \t%rd<3>;\n\
\tld.param.u64 \t%rd1, [demo_kernel_param_0];\n\tmov.u32 \t%r1, %tid.x;\n\tmov.u32 \t%r2, %ctaid.x;\n\
\tadd.s32 \t%r3, %r1, %r2;\n\tadd.s32 \t%r4, %r3, %r2;\n\tadd.s32 \t%r5, %r4, %r2;\n\tadd.s32 \t%r6, %r5, %r2;\n\
\tst.global.u32 \t[%rd1], %r6;\n\tret;\n}\n";

    // One call sniffs the content class (here: PTX) and sizes the model from the input length.
    let packed = kzx::compress(raw);

    // Headers can be read without decoding anything: codec, memory parameter, lengths.
    let info = kzx::inspect(&packed).expect("a stream we just wrote inspects");
    for (i, b) in info.blocks.iter().enumerate() {
        println!(
            "block {i}: codec {} mem_log2 {} raw {} packed {}",
            b.profile.name(),
            b.mem_log2,
            b.raw_len,
            b.packed_len
        );
    }

    // Decoding takes explicit caps: the declared output and the model memory are checked
    // against them before any allocation, so a forged header cannot make the decoder allocate.
    let limits = kzx::Limits {
        max_output: 1 << 20,
        max_memory: 64 << 20,
    };
    let back = kzx::decompress(&packed, &limits).expect("round trip");
    assert_eq!(back, raw);
    println!(
        "{} -> {} bytes ({:.2}x), round trip exact",
        raw.len(),
        packed.len(),
        raw.len() as f64 / packed.len() as f64
    );

    // A cap below the declaration is a typed refusal, not an allocation.
    let tight = kzx::Limits {
        max_output: 16,
        max_memory: 64 << 20,
    };
    match kzx::decompress(&packed, &tight) {
        Err(kzx::Error::OutputCapExceeded { declared, cap }) => {
            println!("refused: declares {declared} bytes, cap {cap}")
        }
        other => panic!("unexpected: {other:?}"),
    }
}
