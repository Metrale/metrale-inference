"""2026-10-23: Cut an nsys capture of a speculative TP serve into the runs the circuit plans, for
the plan-fidelity gate (crates/server/src/cli/circuit_fidelity.rs).

A step is the span from one `--step-kernel` launch to the next. Inside a step, in start order:

  head tail   kernels before the first machinery launch      -> the previous verify's head
  commit      machinery: `--commit-kernel` / `--copy-kernel` / host collectives (unplanned)
  refeed      eager launches after the commit, before `--verify-start` -> unplanned (reported)
  draft       graph-captured launches in the same span      -> the draft run
  verify      `--verify-start` to the step's end            -> the verify run (head tail appended)

Steps are grouped into variants by the multiset of their launches (A = most frequent). Every
segment is written as its ordered kernel list; counts are derived by the reader (one source).

The output is TOML on stdout; the sqlite's SHA-256 is recorded so a stale oracle is detectable.
"""

import argparse
import bisect
import collections
import hashlib
import sqlite3
import sys


def toml_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def launches(path):
    db = sqlite3.connect(f"file:{path}?mode=ro", uri=True)
    return list(
        db.execute(
            "select k.start, s.value, k.graphNodeId is not null "
            "from CUPTI_ACTIVITY_KIND_KERNEL k join StringIds s on s.id = k.shortName "
            "order by k.start"
        )
    )


def steps_of(rows, anchor):
    starts = [r[0] for r in rows if r[1] == anchor]
    if len(starts) < 3:
        sys.exit(f"fewer than 3 `{anchor}` launches: no whole step to cut")
    per = [[] for _ in range(len(starts) - 1)]
    for t, name, graph in rows:
        if starts[0] <= t < starts[-1]:
            per[bisect.bisect_right(starts, t) - 1].append((name, graph))
    return per


def cut(step, a):
    names = [n for n, _ in step]
    machinery = set([a.commit_kernel, a.copy_kernel] + a.host_collective)
    first_commit = next((i for i, n in enumerate(names) if n in machinery), None)
    if first_commit is None or a.verify_start not in names:
        sys.exit("a step without the commit machinery or the verify start: no segment boundary")
    vstart = names.index(a.verify_start)
    seg = {"verify": names[vstart:] + names[:first_commit], "draft": [], "refeed": [], "commit": []}
    for name, graph in step[first_commit:vstart]:
        if name in machinery:
            seg["commit"].append(name)
        elif graph:
            seg["draft"].append(name)
        else:
            seg["refeed"].append(name)
    return seg


def main():
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("sqlite")
    p.add_argument("--source", required=True, help="provenance sentence for the oracle")
    p.add_argument("--rank", type=int, required=True)
    p.add_argument("--verify-rows", type=int, required=True)
    p.add_argument("--draft-rows", type=int, required=True)
    p.add_argument("--step-kernel", required=True)
    p.add_argument("--commit-kernel", required=True)
    p.add_argument("--copy-kernel", required=True)
    p.add_argument("--verify-start", required=True)
    p.add_argument("--host-collective", action="append", required=True)
    a = p.parse_args()

    per = steps_of(launches(a.sqlite), a.step_kernel)
    keys = [frozenset(collections.Counter(n for n, _ in s).items()) for s in per]
    freq = collections.Counter(keys).most_common()
    label = {k: chr(ord("A") + i) for i, (k, _) in enumerate(freq)}

    out = [
        "# Generated by scripts/fidelity/trace_segments.py; do not edit.",
        "schema = 1",
        f"source = {toml_str(a.source)}",
        f"sqlite_sha256 = {toml_str(sha256(a.sqlite))}",
        f"rank = {a.rank}",
        f"step_kernel = {toml_str(a.step_kernel)}",
        f"steps = {len(per)}",
        f"sequence = {toml_str(''.join(label[k] for k in keys))}",
    ]
    for k, n in freq:
        step = per[keys.index(k)]
        seg = cut(step, a)
        out += ["", "[[variant]]", f"name = {toml_str(label[k])}", f"steps = {n}"]
        runs = [
            ("verify", "verify", a.verify_rows),
            ("draft", "draft", a.draft_rows),
            ("refeed", None, None),
            ("commit", None, None),
        ]
        for name, mode, rows in runs:
            out += ["", "[[variant.segment]]", f"name = {toml_str(name)}"]
            if mode:
                out += [f"mode = {toml_str(mode)}", f"rows = {rows}"]
            out.append("kernels = [" + ", ".join(toml_str(x) for x in seg[name]) + "]")
    print("\n".join(out))


if __name__ == "__main__":
    main()
