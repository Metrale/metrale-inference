// =============================================================================
// derive.mjs: everything this repository takes from the brand kit, derived from
// the vendored copy in assets/brand/metrale-assets (pinned by take-assets.sh).
// -----------------------------------------------------------------------------
// The kit (Metrale/metrale-assets) is the single source of every brand asset.
// This script never draws or recolours one; it copies the kit's files to the
// paths this repository serves them from, writes the files that inline them,
// and checks the few hand-written values that must equal the kit's.
//
//   copies     README banners, assets/{logo,favicon}.svg, the book's icons,
//              social card and Manrope font file with its licence
//   writes     book/theme/css/metrale-brand.css  every kit colour as --brand-*
//              book/theme/fonts/fonts-v2.css     the faces, and the kit's fallback face
//              book/theme/metrale.js             the menu-bar logo, inlined
//   checks     head.hbs theme-color is the kit's ground; the book's tokens read
//              the ground, the mark and the accents from --brand-*; the cert
//              generators draw the kit's compact mark; no public file names
//              cyan or the retired face
//
// The Docs workflow runs it with --check after take-assets.sh --check, and
// fails when a file on disk is not what the kit says. After taking a new kit
// release: node assets/brand/derive.mjs, then look at the README and the book.
// =============================================================================

import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(here, '..', '..');
const KIT = join(here, 'metrale-assets');
const CHECK = process.argv.includes('--check');
const SELF = fileURLToPath(import.meta.url); // names the patterns it sweeps for

const kit = (p) => join(KIT, p);
const repo = (p) => join(REPO, p);
const brand = JSON.parse(readFileSync(kit('tokens/brand.json'), 'utf8'));
const pin = readFileSync(join(here, 'metrale-assets.pin'), 'utf8');
const tag = /^tag=(.+)$/m.exec(pin)[1];
const C = brand.color;

// The owner's ruling (2026-10-08): nothing public uses cyan, so the kit's cyan
// is not emitted, and the old cyans may not come back either.
const NO_EMIT = new Set(['cyan']);
const FORBIDDEN = [
  [/#?\b(61ACCC|6FD9EC|5A96BD)\b/i, 'a cyan'],
  [/Urbanist/, 'the retired typeface'],
];

const COPIES = [
  ['svg/logo-horizontal.svg', 'assets/logo.svg'],
  ['favicon.svg', 'assets/favicon.svg'],
  ['svg/logo-horizontal.svg', 'docs/readme/banner-light.svg'],
  ['svg/logo-horizontal-ondark.svg', 'docs/readme/banner-dark.svg'],
  ['favicon.svg', 'book/brand/favicon.svg'],
  ['favicon.ico', 'book/brand/favicon.ico'],
  ['dark/favicon-16.png', 'book/brand/favicon-16.png'],
  ['dark/favicon-32.png', 'book/brand/favicon-32.png'],
  ['dark/favicon-48.png', 'book/brand/favicon-48.png'],
  ['dark/apple-touch-icon-180.png', 'book/brand/apple-touch-icon.png'],
  ['dark/og-image-1200x630.png', 'book/brand/og-image.png'],
  ['fonts/manrope-latin-wght-normal.woff2', 'book/theme/fonts/manrope-latin-wght-normal.woff2'],
  ['fonts/MANROPE-LICENSE.txt', 'book/theme/fonts/MANROPE-LICENSE.txt'],
];

const kebab = (s) => s.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase());
const SOURCE = `assets/brand/metrale-assets (metrale-assets ${tag})`;

const files = new Map();
for (const [from, to] of COPIES) files.set(repo(to), readFileSync(kit(from)));

files.set(
  repo('book/theme/css/metrale-brand.css'),
  `/* Generated by assets/brand/derive.mjs from ${SOURCE}, tokens/brand.json. Do not edit.
   Every colour of the kit by name, except cyan, which nothing public uses.
   css/metrale-tokens.css names its roles from these. */
:root {
${Object.entries(C)
  .filter(([name]) => !NO_EMIT.has(name))
  .map(([name, hex]) => `  --brand-${kebab(name)}: ${hex};`)
  .join('\n')}
  --brand-heading-weight: ${brand.type.headings};
}
`,
);

// mdBook links theme/fonts/fonts.css itself when it has content, at a URL the
// Pages headers cache as immutable for a year, so a reader who cached the
// brand v1 file would never see Manrope. The faces therefore live in a file
// whose name changes with the brand (head.hbs links it), and fonts.css stays
// empty: mdBook then links nothing of its own and still copies theme/fonts/.
// A change to the faces' content needs a new name here and in head.hbs.
files.set(repo('book/theme/fonts/fonts.css'), '');
files.set(
  repo('book/theme/fonts/fonts-v2.css'),
  `/* Generated by assets/brand/derive.mjs. Do not edit.
   The book's faces, self hosted beside the pages. head.hbs links this file at
   fonts/fonts-v2.css; mdBook copies every file in theme/fonts/ beside it.

   Manrope is the kit's typeface (variable, weights 200 to 800, latin), from
   ${SOURCE}, followed by the kit's metric-matched
   fallback face, verbatim from its fonts/manrope-fallback.css. IBM Plex Mono
   carries code and labels, which the kit does not cover. Both are SIL Open
   Font License; the licence texts ride along beside them. */
@font-face {
  font-family: 'Manrope';
  font-style: normal;
  font-weight: 200 800;
  font-display: swap;
  src: url('manrope-latin-wght-normal.woff2') format('woff2');
}
${readFileSync(kit('fonts/manrope-fallback.css'), 'utf8').trim()}
@font-face {
  font-family: 'IBM Plex Mono';
  font-style: normal;
  font-weight: 400;
  font-display: swap;
  src: url('ibm-plex-mono-latin-400-normal.woff2') format('woff2');
}
@font-face {
  font-family: 'IBM Plex Mono';
  font-style: normal;
  font-weight: 600;
  font-display: swap;
  src: url('ibm-plex-mono-latin-600-normal.woff2') format('woff2');
}
`,
);

// The book has no bundler, so its menu-bar script carries the logo inline. The
// book's palette is dark in every mdBook theme (css/variables.css), so the
// logo is the kit's dark-ground cut. It replaces the title mdBook sets in type,
// linked to the front page, with "Engine docs" beside it; the link's name keeps
// the title for assistive technology. css/wordmark.css places it. The script is
// linked at the end of the body, below the menu bar, so it places the logo as
// soon as it runs, before the first paint, rather than waiting for the parse to
// end: mdBook's own scripts are deferred (index.hbs), and the title would be
// painted in type first and then swapped.
const ondark = readFileSync(kit('svg/logo-horizontal-ondark.svg'), 'utf8').trim();
files.set(
  repo('book/theme/metrale.js'),
  `// Generated by assets/brand/derive.mjs from ${SOURCE}, svg/logo-horizontal-ondark.svg. Do not edit.
// The Metrale logo in the book's menu bar, with "Engine docs" beside it.
(function () {
  var logo = ${JSON.stringify(ondark)};
  function place() {
    var h = document.querySelector('h1.menu-title');
    if (!h || h.querySelector('.metrale-lockup')) return;
    var root = typeof window.path_to_root === 'string' ? window.path_to_root : '';
    h.innerHTML =
      '<a class="metrale-lockup" href="' +
      root +
      'index.html" aria-label="The Metrale Engine Book, front page">' +
      logo +
      '</a><span class="metrale-docs" aria-hidden="true">Engine docs</span>';
  }
  if (document.querySelector('h1.menu-title')) place();
  else document.addEventListener('DOMContentLoaded', place);
})();
`,
);

const problems = [];

// Hand-written values that must equal the kit's.
const read = (p) => readFileSync(repo(p), 'utf8');
const head = read('book/theme/head.hbs');
if (!head.includes(`<meta name="theme-color" content="${C.ground}">`))
  problems.push(`book/theme/head.hbs: theme-color is not the kit's ground ${C.ground}`);
if (!head.includes(`<link rel="stylesheet" href="{{ path_to_root }}fonts/fonts-v2.css">`))
  problems.push('book/theme/head.hbs: does not link fonts/fonts-v2.css');
// head.hbs preloads the faces the first paint sets; each must be one fonts-v2.css declares.
const facesCss = files.get(repo('book/theme/fonts/fonts-v2.css'));
for (const face of ['manrope-latin-wght-normal.woff2', 'ibm-plex-mono-latin-400-normal.woff2']) {
  if (!facesCss.includes(`url('${face}')`))
    problems.push(`book/theme/fonts/fonts-v2.css: no longer declares ${face}, which head.hbs preloads`);
  if (!head.includes(`<link rel="preload" href="{{ path_to_root }}fonts/${face}" as="font" type="font/woff2" crossorigin>`))
    problems.push(`book/theme/head.hbs: does not preload fonts/${face}`);
}
const tokens = read('book/theme/css/metrale-tokens.css');
const block = (sel) => {
  const i = tokens.indexOf(`${sel} {`);
  return i < 0 ? '' : tokens.slice(i, tokens.indexOf('\n}', i));
};
for (const [sel, decl] of [
  [':root', '--bg: var(--brand-ground);'],
  [':root', '--mark: var(--brand-copper);'],
  [':root', '--accent: var(--brand-copper-light);'],
  ['[data-theme="light"]', '--accent: var(--brand-copper-deep);'],
]) {
  if (!block(sel).includes(decl)) problems.push(`book/theme/css/metrale-tokens.css: ${sel} lacks \`${decl}\``);
}

// The certificate generators draw the kit's compact mark, path for path.
const compact = readFileSync(kit('svg/mark-compact.svg'), 'utf8');
const gen = read('.github/scripts/certgen/gen_badges.py');
for (const [, d] of compact.matchAll(/ d="([^"]+)"/g)) {
  if (!gen.includes(d)) problems.push(`.github/scripts/certgen/gen_badges.py: lacks the kit's compact mark path ${d}`);
}

// No public file names cyan or the retired face. The vendored kit is exempt:
// it is the kit verbatim, and its tokens still list a cyan this repo never emits.
const SWEEP = ['README.md', 'assets', 'book/theme', 'book/brand', 'docs/readme', 'docs/diagrams', '.github/scripts/certgen'];
const TEXT = /\.(md|svg|css|js|mjs|hbs|py|txt|html)$/;
function* walk(p) {
  if (statSync(p).isDirectory()) {
    if (p === KIT) return;
    for (const e of readdirSync(p)) yield* walk(join(p, e));
  } else if (TEXT.test(p) && p !== SELF) yield p;
}
for (const top of SWEEP) {
  for (const f of walk(repo(top))) {
    const text = files.has(f) ? String(files.get(f)) : readFileSync(f, 'utf8');
    for (const [re, what] of FORBIDDEN) if (re.test(text)) problems.push(`${relative(REPO, f)}: names ${what} (${re.exec(text)[0]})`);
  }
}

let stale = 0;
for (const [file, content] of files) {
  let current = null;
  try {
    current = readFileSync(file);
  } catch {}
  if (current && Buffer.compare(current, Buffer.from(content)) === 0) continue;
  stale++;
  if (CHECK) problems.push(`${relative(REPO, file)}: not what ${SOURCE} gives; run node assets/brand/derive.mjs`);
  else writeFileSync(file, content);
}

if (problems.length) {
  for (const p of problems) console.error(`derive: ${p}`);
  process.exit(1);
}
console.log(CHECK ? `derive: current with metrale-assets ${tag}` : `derive: wrote ${stale} file(s) from metrale-assets ${tag}`);
